const POOL = ['王燕勤', '周波', '罗德东', '董丹璐', '杨鈊汉', '张伟', '李娜', '王强'];
const COLORS = ['#2f6bff', '#7c5cff', '#00a6a6', '#e6781a', '#d6336c', '#3d9970'];

function hash(str) {
  let h = 0;
  for (let i = 0; i < str.length; i++) h = (h * 31 + str.charCodeAt(i)) >>> 0;
  return h;
}

function staffFor(key) {
  if (key === '数据服务/API数据') return ['王燕勤', '周波'];
  const h = hash(key);
  const a = POOL[h % POOL.length];
  let b = POOL[(h >>> 4) % POOL.length];
  if (b === a) b = POOL[(POOL.indexOf(a) + 3) % POOL.length];
  return [a, b];
}

function colorFor(name) {
  return COLORS[hash(name) % COLORS.length];
}

