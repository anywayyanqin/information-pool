const ORG_DEPTS = [];
const ORG_USERS = [];
const ORG_USERS_BY_ID = {};
const ORG_DEPTS_BY_ID = {};
const ORG_DEPTID_BY_USER = {};
/* 与 mock.js 演示账号重名时复用同一个 id，避免同一个人出现两个身份 */
function orgMatchedUser(name) {
  var list = (typeof USERS !== 'undefined' && USERS) ? USERS : [];
  for (var i = 0; i < list.length; i++) if (list[i].name === name) return list[i];
  return null;
}
ORG_SOURCE.forEach(function (row, di) {
  var names = String(row[1] || '').split('、').filter(Boolean);
  var dept = { id: 'od' + (di + 1), name: row[0], userIds: [] };
  names.forEach(function (name, ei) {
    var known = orgMatchedUser(name);
    var uid = known ? known.id : 'ou' + (di + 1) + '_' + (ei + 1);
    dept.userIds.push(uid);
    if (!ORG_DEPTID_BY_USER[uid]) ORG_DEPTID_BY_USER[uid] = dept.id;
    if (known) return;
    var u = { id: uid, name: name, dept: row[0], role: 'staff', title: '' };
    ORG_USERS.push(u);
    ORG_USERS_BY_ID[uid] = u;
  });
  ORG_DEPTS.push(dept);
  ORG_DEPTS_BY_ID[dept.id] = dept;
});
